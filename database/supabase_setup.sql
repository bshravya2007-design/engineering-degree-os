-- 1. Create scores table

CREATE TABLE IF NOT EXISTS public.scores (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id UUID NOT NULL REFERENCES auth.users(id)
        ON DELETE CASCADE DEFAULT auth.uid(),
    course_code TEXT NOT NULL,
    assessment_name TEXT NOT NULL,
    marks_obtained NUMERIC NOT NULL,
    total_marks NUMERIC NOT NULL,
    exam_date DATE,
    created_at TIMESTAMPTZ DEFAULT NOW(),

    CONSTRAINT valid_marks CHECK (
        marks_obtained >= 0
        AND total_marks > 0
        AND marks_obtained <= total_marks
    )
);

-- 2. Enable Row Level Security

ALTER TABLE public.scores ENABLE ROW LEVEL SECURITY;

-- 3. Allow users to view their own scores

CREATE POLICY "Users can view their own scores"
ON public.scores
FOR SELECT
TO authenticated
USING (auth.uid() = user_id);

-- 4. Allow users to insert their own scores

CREATE POLICY "Users can insert their own scores"
ON public.scores
FOR INSERT
TO authenticated
WITH CHECK (auth.uid() = user_id);

-- 5. Allow users to update their own scores

CREATE POLICY "Users can update their own scores"
ON public.scores
FOR UPDATE
TO authenticated
USING (auth.uid() = user_id)
WITH CHECK (auth.uid() = user_id);

-- 6. Allow users to delete their own scores

CREATE POLICY "Users can delete their own scores"
ON public.scores
FOR DELETE
TO authenticated
USING (auth.uid() = user_id);

-- 7. Grant permissions to authenticated users

GRANT SELECT, INSERT, UPDATE, DELETE
ON public.scores TO authenticated;
